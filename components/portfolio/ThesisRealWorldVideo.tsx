function VideoDemo({ item, featured = false }: { item: ClipInfo; featured?: boolean }) {
  const [attempt, setAttempt] = useState<"local" | "source" | "unavailable">("local");
  const externalVideo = `https://media.githubusercontent.com/media/${sourceRepoPath}/main/${item.path}`;
  const githubFile = `${SOURCE_REPO}/blob/main/${item.path}`;
  const currentVideo = attempt === "local" ? `/api/thesis-clips/${item.key}` : externalVideo;

  return (
    <article className="overflow-hidden rounded-[1.3rem] border border-[var(--line)] bg-[var(--panel)]">
      <div className="relative overflow-hidden bg-[#e7efe8]">
        {attempt !== "unavailable" ? (
          <video
            key={currentVideo}
            src={currentVideo}
            poster={item.poster}
            controls
            muted
            playsInline
            loop
            autoPlay={featured}
            preload="metadata"
            className="block aspect-video h-auto w-full bg-[#eff4ef] object-contain"
            aria-label={`Original thesis-generated trajectory prediction animation for ${item.title}, ${item.sample}`}
            onError={() => setAttempt((old) => old === "local" ? "source" : "unavailable")}
          >
            Your browser does not support MP4 video.
          </video>
        ) : (
          <a href={githubFile} target="_blank" rel="noopener noreferrer" className="group relative block aspect-video overflow-hidden">
            <Image src={item.poster} alt={`Original thesis figure, ${item.title}, ${item.sample}`} fill
              unoptimized sizes="(max-width: 768px) 100vw, 60vw" className="object-contain"/>
            <span className="absolute inset-0 flex flex-col items-center justify-center gap-3 bg-[#103a2a]/65 p-5 text-center text-sm font-semibold text-white">
              <FiPlay size={32} aria-hidden="true"/> Video could not load here · open on GitHub
            </span>
          </a>
        )}
      </div>
      <div className="flex flex-wrap items-start justify-between gap-4 p-4 sm:p-5">
        <div>
          <p className="font-mono text-[10px] font-semibold uppercase tracking-[0.13em] text-[var(--accent)]">{item.sample} / original thesis animation</p>
          <h3 className="mt-2 font-serif text-2xl tracking-[-.04em]">{item.title}</h3>
          <p className="mt-1 text-xs leading-6 text-[var(--muted)]">{item.subtitle}</p>
        </div>
        <a href={githubFile} target="_blank" rel="noopener noreferrer"
           className="inline-flex items-center gap-1.5 text-xs font-semibold text-[var(--accent)] underline underline-offset-4">
          Original file <FiExternalLink aria-hidden="true" />
        </a>
      </div>
    </article>
  );
}

